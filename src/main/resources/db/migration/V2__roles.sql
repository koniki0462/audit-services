-- Application roles: a global catalogue (not per organization). updated_at is maintained by the application
-- (Hibernate @UpdateTimestamp), not a trigger, so this runs on H2 as well as PostgreSQL.
CREATE TABLE roles (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)   NOT NULL,
    description TEXT,
    is_active   BOOLEAN       DEFAULT TRUE NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version     BIGINT        DEFAULT 0 NOT NULL,
    CONSTRAINT roles_name_uq UNIQUE (name)
);

